export const SPECIES_BY_ID = Object.fromEntries(SPECIES.map((item) => [item.id, item]));

export function findRecipe(materialIds) {
  const key = setKey(materialIds);
  return RECIPES.find((recipe) => recipe.key === key) ?? null;
}

export function getSpecies(speciesId) {
  return SPECIES_BY_ID[speciesId] ?? SPECIES_BY_ID.failed_gunk;
}

export function rarityLabel(rarity) {
  return RARITY_LABELS[rarity] ?? rarity;
}

export function allSpecies() {
  return SPECIES;
}
